#!/usr/bin/env node
/**
 * build-index-migration.js
 *
 * Turns the reviewed files in scripts/indices/current/ into ONE idempotent SQL
 * migration (single transaction, safe to re-run):
 *   1. domain corrections from domain-fixes.csv (rename in place, or merge into an
 *      existing row) — ids, index links and scan history are preserved;
 *   2. index rows for the newly tracked indices;
 *   3. current constituents: new domains inserted, existing ones NEVER overwritten
 *      (no change to their name / country / sector); index links upserted;
 *   4. companies that left a refreshed index are unlinked from it, not deleted —
 *      they stay monitored and show up under "Other";
 *   5. a daily tls_scan is assigned to every active domain that lacks one.
 *
 * Usage: node scripts/build-index-migration.js > sql/migrations/<date>_index_refresh.sql
 */
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, 'indices', 'current');
const TODAY = new Date().toISOString().slice(0, 10);

const INDICES = {
  sp500:          { name: 'S&P 500',       description: 'Americas - United States' },
  ftse100:        { name: 'FTSE 100',      description: 'Europe - United Kingdom, 100 largest companies on the London Stock Exchange' },
  dax:            { name: 'DAX',           description: 'Europe - Germany, 40 largest companies on the Frankfurt Stock Exchange' },
  cac40:          { name: 'CAC 40',        description: 'Europe - France, 40 largest companies on Euronext Paris' },
  ibex35:         { name: 'IBEX 35',       description: 'Europe - Spain, 35 most liquid companies on the Bolsa de Madrid' },
  'euro-stoxx50': { name: 'Euro Stoxx 50', description: 'Europe - Eurozone, 50 blue-chip companies' },
};

// Reviewed substitutions for constituents (stale names, regional sites, subsidiaries).
const MEMBER_DOMAIN_FIXES = {
  'drpeppersnapplegroup.com': 'keurigdrpepper.com',
  'smurfitkappa.com': 'smurfitwestrock.com',
  'chk.com': 'expandenergy.com',
  'deutschepost.com': 'dpdhl.com',            // Deutsche Post = DHL Group, already tracked
  'fundacionunicaja.com': 'unicaja.es',       // the foundation, not the bank
  'alliancetrust.co.uk': 'alliancewitan.com',
  'africa.airtel.com': 'airtel.africa',
  'thephoenixgroup.com': 'standardlifeplc.com',
};
const MISSING_WEBSITES = {
  'Insulet Corporation': 'insulet.com',
  'Lumentum': 'lumentum.com',
  'Norwegian Cruise Line Holdings': 'nclhltd.com',
  'Solaria': 'solariaenergia.com',
};
// Extra corrections to existing rows found during review.
const EXTRA_DOMAIN_FIXES = [['phoenixgroup.eu', 'standardlifeplc.com']];
const DEACTIVATE = [['rapidcreditboosters.com', 'Not an S&P 500 company (bad source data)']];
const METADATA = [
  ['ipgphotonics.com', { country: 'United States' }],
  ['davita.com', { company_name: 'DaVita' }],
  ['standardlifeplc.com', { company_name: 'Standard Life', country: 'United Kingdom' }],
];

function readCsv(file) {
  return fs.readFileSync(file, 'utf8').trim().split('\n').slice(1).map((line) => {
    const cells = []; let cur = ''; let q = false;
    for (const ch of line) {
      if (ch === '"') { q = !q; continue; }
      if (ch === ',' && !q) { cells.push(cur); cur = ''; continue; }
      cur += ch;
    }
    cells.push(cur);
    return cells;
  });
}
const lit = (v) => (v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`);

// 1. domain fixes (only verified, unambiguous rows)
const fixes = readCsv(path.join(DIR, 'domain-fixes.csv'))
  .filter(([, oldD, newD, , verified]) => oldD && newD && !newD.startsWith('(') && oldD !== newD
    && /^ok/.test(verified || '') && !/confirmar|inconclusivo/.test(verified || ''))
  .map(([, oldD, newD]) => [oldD, newD])
  .concat(EXTRA_DOMAIN_FIXES);
const fixMap = new Map(fixes);
const finalDomain = (d) => {
  let x = d;
  for (let i = 0; i < 3; i++) x = fixMap.get(x) || MEMBER_DOMAIN_FIXES[x] || x;
  return x;
};

// 2/3. members
const members = [];
for (const key of Object.keys(INDICES)) {
  const seen = new Set();
  for (const c of readCsv(path.join(DIR, `${key}.csv`))) {
    const [rank, domain, company, country, sector] = c;
    const d = finalDomain(domain || MISSING_WEBSITES[company] || '');
    if (!d || seen.has(d)) continue;
    seen.add(d);
    members.push([key, d, Number(rank), company, country, sector === 'Industrials' ? 'Other' : sector]);
  }
}

const out = [];
const p = (s) => out.push(s);
p(`-- PQC Readiness Tracker — index refresh ${TODAY}`);
p('-- Generated by scripts/build-index-migration.js from the reviewed files in scripts/indices/current/.');
p('-- Single transaction, idempotent (safe to re-run). Never deletes domains or scan history.');
p('begin;\n');

p('-- 1. Domain corrections --------------------------------------------------------');
p('create temp table _fix (old_domain text primary key, new_domain text not null) on commit drop;');
p(`insert into _fix values\n  ${fixes.map(([a, b]) => `(${lit(a)}, ${lit(b)})`).join(',\n  ')};`);
p(`-- 1a. target already tracked: move the index links to it and retire the old row
insert into domain_indexes (domain_id, index_id, rank, year)
  select t.id, di.index_id, di.rank, di.year
  from _fix f join domains o on o.domain = f.old_domain
              join domains t on t.domain = f.new_domain
              join domain_indexes di on di.domain_id = o.id
  on conflict (domain_id, index_id) do nothing;
delete from domain_indexes di
  using _fix f, domains o, domains t
  where o.domain = f.old_domain and t.domain = f.new_domain and di.domain_id = o.id;
update domains o
  set active = false,
      notes = concat_ws(E'\\n', nullif(o.notes, ''), 'Merged into ' || f.new_domain || ' (${TODAY})'),
      updated_at = now()
  from _fix f
  where o.domain = f.old_domain and o.active
    and exists (select 1 from domains t where t.domain = f.new_domain);
-- 1b. otherwise rename in place (keeps id, index links and scan history)
update domains d set domain = f.new_domain, updated_at = now()
  from _fix f
  where d.domain = f.old_domain
    and not exists (select 1 from domains t where t.domain = f.new_domain);`);
for (const [d, fields] of METADATA) {
  p(`update domains set ${Object.entries(fields).map(([k, v]) => `${k} = ${lit(v)}`).join(', ')}, updated_at = now() where domain = ${lit(d)};`);
}
for (const [d, why] of DEACTIVATE) {
  p(`update domains set active = false, notes = concat_ws(E'\\n', nullif(notes, ''), ${lit(`${why} — deactivated ${TODAY}`)}), updated_at = now() where domain = ${lit(d)} and active;`);
}

p('\n-- 2. Indices -------------------------------------------------------------------');
p(`insert into indexes (key, name, description, year, active) values\n  ${Object.entries(INDICES).map(([k, v]) => `(${lit(k)}, ${lit(v.name)}, ${lit(v.description)}, 2026, true)`).join(',\n  ')}\non conflict (key) do nothing;`);

p('\n-- 3. Current constituents -------------------------------------------------------');
p('create temp table _member (index_key text, domain text, rank int, company_name text, country text, sector text, primary key (index_key, domain)) on commit drop;');
p(`insert into _member values\n  ${members.map((m) => `(${m.map(lit).join(', ')})`).join(',\n  ')};`);
p(`-- new organisations only; existing rows keep their name/country/sector untouched
insert into domains (domain, company_name, country, sector, active, notes)
  select distinct on (domain) domain, company_name, country, sector, true, 'Source: index constituents (Wikipedia/Wikidata, ${TODAY})'
  from _member order by domain, rank
  on conflict (domain) do nothing;
insert into domain_indexes (domain_id, index_id, rank, year)
  select d.id, i.id, m.rank, 2026
  from _member m join domains d on d.domain = m.domain join indexes i on i.key = m.index_key
  on conflict (domain_id, index_id) do update set rank = excluded.rank, year = excluded.year;`);

p('\n-- 4. Companies that left a refreshed index: unlink only (they stay monitored → "Other")');
p(`delete from domain_indexes di
  using indexes i
  where di.index_id = i.id
    and i.key in (${Object.keys(INDICES).map(lit).join(', ')})
    and not exists (select 1 from _member m join domains d on d.domain = m.domain
                    where m.index_key = i.key and d.id = di.domain_id);`);

p('\n-- 5. Daily TLS scan for every active domain that has none ------------------------');
p(`insert into domain_tests (domain_id, test_type_id, active, schedule_enabled, schedule_frequency, schedule_time, next_run_at)
  select d.id, tt.id, true, true, 'daily', '02:00', (date_trunc('day', now() at time zone 'utc') + interval '1 day 2 hours') at time zone 'utc'
  from domains d
  cross join (select id from test_types where runner_type = 'tls_scan' and active order by created_at limit 1) tt
  where d.active
  on conflict (domain_id, test_type_id) do nothing;`);

p('\n-- 6. Make /stats recompute from the new membership on its next request');
p('delete from stats_cache;');

p('\n-- 7. Summary (the result shown by the SQL editor) ------------------------------');
p(`select 'index: ' || i.name as item, count(di.id)::int as value
  from indexes i left join domain_indexes di on di.index_id = i.id group by i.name
union all select 'active domains', count(*)::int from domains where active
union all select 'inactive domains', count(*)::int from domains where not active
union all select 'active, in no index ("Other")', count(*)::int from domains d
  where d.active and not exists (select 1 from domain_indexes di where di.domain_id = d.id)
union all select 'active without a tls_scan', count(*)::int from domains d
  where d.active and not exists (select 1 from domain_tests t where t.domain_id = d.id)
order by 1;`);
p('\ncommit;');
process.stdout.write(out.join('\n') + '\n');
console.error(`fixes: ${fixes.length} | members: ${members.length} across ${Object.keys(INDICES).length} indices`);
